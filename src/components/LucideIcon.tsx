interface LucideIconProps {
  name: string;
  size?: number | string;
  className?: string;
  color?: string;
  strokeWidth?: number;
  [key: string]: any;
}

export default function LucideIcon({
  name,
  size = 16,
  className = '',
  color,
  strokeWidth = 2,
  ...rest
}: LucideIconProps) {
  const normalized = name ? name.charAt(0).toUpperCase() + name.slice(1) : '';
  const Component = ICON_MAP[name] || ICON_MAP[normalized] || Sparkles;

  return <Component size={size} className={className} color={color} strokeWidth={strokeWidth} {...rest} />;
}
